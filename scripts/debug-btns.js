import { chromium } from "playwright";
import path from "path";
import { fileURLToPath } from "url";
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const distDir = path.join(__dirname, "../dist");
const optionsUrl = "file:///" + distDir.replace(/\\/g, "/") + "/options.html";
const MOCK = `(function(){window.chrome={storage:{local:{get(k,cb){if(cb)cb({});return Promise.resolve({})},set(_,cb){if(cb)cb();return Promise.resolve()}}},runtime:{getURL:p=>p,openOptionsPage:()=>{},sendMessage:()=>{},lastError:null},downloads:{showDefaultFolder:()=>{}}};})();`;
const browser = await chromium.launch({ executablePath:"C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless:true, args:["--no-sandbox"] });
const ctx = await browser.newContext({ viewport:{ width:1200, height:820 } });
const p = await ctx.newPage();
await p.addInitScript(MOCK);
await p.goto(optionsUrl, { waitUntil:"networkidle" });
await p.waitForTimeout(1000);
const texts = await p.evaluate(() => [...document.querySelectorAll("button")].map(b => b.textContent?.trim().slice(0,50)));
console.log(JSON.stringify(texts, null, 2));
await browser.close();
